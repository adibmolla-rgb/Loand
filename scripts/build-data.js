/* Usage: node scripts/build-data.js [path/to/workbook.xlsx] [--strict]

   Converts the Loand research workbook into:
     data/json/<sheet>.json   one typed JSON file per sheet
     data/json/meta.json      release date, row counts, source count
     data/research.js         legacy single-file bundle the current pages load

   Validates first and fails with a clear message on violations.
   --strict also fails on warnings (known workbook defects).
   With no path, the newest Loand_UK_Lender_Research_*.xlsx in data/ or tools/ is used. */

const fs = require("fs");
const path = require("path");
const { slug, validate } = require("./lib-data");
const { ROOT, findWorkbooks, readWorkbookTables } = require("./lib-workbook");

const args = process.argv.slice(2);
const strict = args.includes("--strict");
const given = args.find(arg => !arg.startsWith("--"));

function findWorkbook() {
    if (given) return path.resolve(given);
    const found = findWorkbooks();
    if (!found.length) throw new Error("No Loand_UK_Lender_Research_*.xlsx found in data/ or tools/");
    return found[found.length - 1];
}

function main() {
    const source = findWorkbook();
    const tables = readWorkbookTables(source);

    const { errors, warnings } = validate(tables);
    warnings.forEach(w => console.warn("WARNING:", w));
    if (errors.length || (strict && warnings.length)) {
        const list = [...errors, ...(strict ? warnings : [])];
        console.error(`\nData validation FAILED (${list.length} problem${list.length === 1 ? "" : "s"}) in ${path.basename(source)}:`);
        list.slice(0, 50).forEach(e => console.error("  - " + e));
        if (list.length > 50) console.error(`  ...and ${list.length - 50} more`);
        process.exit(1);
    }

    const date = /(\d{4}-\d{2}-\d{2})/.exec(path.basename(source));
    const rowCounts = Object.fromEntries(Object.entries(tables).map(([name, table]) => [slug(name), table.rows.length]));
    const meta = {
        data_as_at: date ? date[1] : null,
        source_file: path.basename(source),
        row_counts: rowCounts,
        source_count: tables.Sources.rows.length,
        warnings
    };

    const outDir = path.join(ROOT, "data", "json");
    fs.rmSync(outDir, { recursive: true, force: true });
    fs.mkdirSync(outDir, { recursive: true });
    const bundle = { meta: { data_as_at: meta.data_as_at, source_file: meta.source_file, sheet_notes: {} } };
    for (const [name, table] of Object.entries(tables)) {
        fs.writeFileSync(path.join(outDir, slug(name) + ".json"), JSON.stringify(table.rows, null, 1) + "\n");
        bundle[slug(name)] = table.rows;
    }
    fs.writeFileSync(path.join(outDir, "meta.json"), JSON.stringify(meta, null, 1) + "\n");
    // Tiny script for pages that only need the release date (e.g. the home page footer).
    fs.writeFileSync(path.join(ROOT, "data", "meta.js"),
        "/* AUTO-GENERATED by scripts/build-data.js. Do not edit by hand. */\n" +
        "window.LOAND_META = " + JSON.stringify({ data_as_at: meta.data_as_at, source_count: meta.source_count }) + ";\n");
    fs.writeFileSync(path.join(ROOT, "data", "research.js"),
        `/* AUTO-GENERATED from ${meta.source_file} by scripts/build-data.js.\n   Do not edit by hand: fix the spreadsheet and re-run the script. */\n` +
        "window.LOAND_RESEARCH = " + JSON.stringify(bundle, null, 1) + ";\n");

    console.log(`Built ${Object.keys(tables).length} sheets from ${meta.source_file} (data as at ${meta.data_as_at}), ${meta.source_count} sources.`);
}

try { main(); } catch (error) { console.error("Build failed:", error.message); process.exit(1); }
